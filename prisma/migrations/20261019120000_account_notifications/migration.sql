-- Durable application account notifications; no historical backfill.
CREATE TABLE `account_notifications` (
  `id` CHAR(36) NOT NULL,
  `kind` VARCHAR(32) NOT NULL,
  `provision_id` CHAR(36) NOT NULL,
  `application_id` CHAR(36) NOT NULL,
  `user_id` CHAR(36) NOT NULL,
  `recipient_email` VARCHAR(191) NOT NULL,
  `qq_normalized` VARCHAR(32) NOT NULL,
  `credential_created` BOOLEAN NOT NULL,
  `credential_version` INTEGER NOT NULL,
  `status` VARCHAR(16) NOT NULL,
  `attempt_count` INTEGER NOT NULL DEFAULT 0,
  `round_attempt_count` INTEGER NOT NULL DEFAULT 0,
  `next_attempt_at` DATETIME(3) NOT NULL,
  `claim_id` CHAR(36) NULL,
  `lease_expires_at` DATETIME(3) NULL,
  `last_attempt_at` DATETIME(3) NULL,
  `last_error_code` VARCHAR(64) NULL,
  `accepted_at` DATETIME(3) NULL,
  `message_id` VARCHAR(191) NULL,
  `created_at` DATETIME(3) NOT NULL,
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `account_notifications_provision_kind_uq` (`provision_id`, `kind`),
  INDEX `account_notifications_due_idx` (`status`, `next_attempt_at`),
  INDEX `account_notifications_lease_idx` (`status`, `lease_expires_at`),
  INDEX `account_notifications_application_idx` (`application_id`),
  INDEX `account_notifications_user_idx` (`user_id`),
  CONSTRAINT `account_notifications_provision_fk` FOREIGN KEY (`provision_id`) REFERENCES `account_provisions` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `account_notifications_application_fk` FOREIGN KEY (`application_id`) REFERENCES `join_applications` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `account_notifications_user_fk` FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci ENGINE=InnoDB;
